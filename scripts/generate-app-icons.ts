/**
 * One icon family: every app's mark is the white glyph of `apps/<app>/public/icons/logo.svg` on the brand navy. This
 * script rebuilds from those svgs the PWA sizes, the apple touch icon, the badge, `logo-64.png`, `favicon.ico` of each app
 * and `packages/ui/src/components/layout/platform-marks.ts` (the same glyphs, used by the sidebar and the app switcher).
 * Staff has no hand-drawn svg yet: its glyph is defined here. Run: `bun scripts/generate-app-icons.ts`.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import sharp from "sharp"

const NAVY = "#273D88"
const APPS = ["sp", "staff", "admin", "lms", "library", "admission", "id"] as const
const STAFF_PATH =
  "M160 100h180a30 30 0 0 1 30 30v240a30 30 0 0 1-30 30H160a30 30 0 0 1-30-30V130a30 30 0 0 1 30-30Zm0 30v240h180V130H160ZM200 190h100v28H200ZM200 250h100v28H200Z"

const root = join(import.meta.dir, "..")
const marks: Record<string, { paths: string[]; evenodd: boolean }> = {}
for (const app of APPS) {
  const file = join(root, "apps", app, "public/icons/logo.svg")
  if (app === "staff") {
    marks[app] = { paths: [STAFF_PATH], evenodd: true }
    continue
  }
  const svg = readFileSync(file, "utf8")
  const paths = [...svg.matchAll(/<path[^>]*?\sd="([^"]+)"[^>]*?fill="white"/g)].map((m) => m[1] as string)
  if (paths.length === 0) throw new Error(`no white glyph in ${file}`)
  marks[app] = { paths, evenodd: false }
}

const glyph = (app: string, fill: string) =>
  marks[app]!.paths.map(
    (d) => `<path d="${d}" fill="${fill}"${marks[app]!.evenodd ? ' fill-rule="evenodd"' : ""}/>`,
  ).join("")
/** `scale` < 1 keeps the glyph inside the maskable safe zone. */
const tile = (app: string, scale = 1, tileFill = NAVY, glyphFill = "white") =>
  `<svg width="500" height="500" viewBox="0 0 500 500" fill="none" xmlns="http://www.w3.org/2000/svg">` +
  (tileFill === "none" ? "" : `<rect width="500" height="500" fill="${tileFill}"/>`) +
  `<g transform="translate(250 250) scale(${scale}) translate(-250 -250)">${glyph(app, glyphFill)}</g></svg>`

const png = (svg: string, size: number) => sharp(Buffer.from(svg), { density: 300 }).resize(size, size).png().toBuffer()

for (const app of APPS) {
  const dir = join(root, "apps", app, "public")
  const icons = join(dir, "icons")
  mkdirSync(icons, { recursive: true })
  writeFileSync(join(icons, "logo.svg"), tile(app) + "\n")
  const any = tile(app)
  writeFileSync(join(icons, "icon-192.png"), await png(any, 192))
  writeFileSync(join(icons, "apple-touch-icon.png"), await png(any, 180))
  writeFileSync(join(icons, "logo-64.png"), await png(any, 64))
  if (app !== "id") {
    writeFileSync(join(icons, "icon-512.png"), await png(any, 512))
    writeFileSync(join(icons, "icon-maskable-512.png"), await png(tile(app, 0.8), 512))
    writeFileSync(join(icons, "badge-96.png"), await png(tile(app, 1, "none", "white"), 96))
  }
  const sizes = await Promise.all([16, 32, 48].map((size) => png(any, size)))
  const tmp = sizes.map((buffer, i) => {
    const path = `/tmp/ihsp-ico-${app}-${i}.png`
    writeFileSync(path, buffer)
    return path
  })
  const proc = Bun.spawnSync(["magick", ...tmp, join(dir, "favicon.ico")])
  if (proc.exitCode !== 0) throw new Error(`favicon.ico of ${app}: ${proc.stderr.toString()}`)
}

const body = APPS.map(
  (app) =>
    `  ${app}: { paths: [${marks[app]!.paths.map((d) => JSON.stringify(d)).join(", ")}], evenodd: ${marks[app]!.evenodd} },`,
).join("\n")
writeFileSync(
  join(root, "packages/ui/src/components/layout/platform-marks.ts"),
  `// Generated by scripts/generate-app-icons.ts from apps/<app>/public/icons/logo.svg. Do not edit by hand.
import type { PlatformLink } from "./user-menu"

/** The white glyph of each app's favicon and PWA icon, on a 500 x 500 canvas. */
export const PLATFORM_MARKS: Record<PlatformLink["key"], { paths: string[]; evenodd: boolean }> = {
${body}
}
`,
)
